/**
 * A tsconfig for @stryker-mutator/typescript-checker that leaves the project's
 * Bun tests out of type checking.
 *
 * The checker type-checks every mutant against the program of its
 * `tsconfigFile` and re-checks every file that depends on the mutated one. When
 * that tsconfig includes the tests, every mutant in a widely imported module
 * re-checks the test suite too. {@link withTestFilesExcludedFromTypeCheck}
 * derives, at config time, a tsconfig that extends the project's own and lists
 * only the code under test, and points the checker at it.
 *
 * No plugin can do this unasked: Stryker freezes its options before it creates
 * any plugin, and starts the checker processes before any test runner exists.
 */

import { readFile, rename, rm, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import type { PartialStrykerOptions } from '@stryker-mutator/api/core';
import { glob } from 'tinyglobby';
import type * as TypeScript from 'typescript';
import { splitBunConfigArg } from './utils/bun-args.js';
import { readBunfigTestPreloads } from './utils/bunfig-sanitizer.js';
import { discoverTestFiles } from './utils/test-file-discovery.js';

type TS = typeof TypeScript;

/**
 * Stand-in for Stryker's default `mutate` patterns, which all match under these
 * directories. Matching them whole over-approximates, which is safe: a file
 * that `mutate` covers is only ever kept in the check.
 */
const DEFAULT_MUTATE_PATTERNS = ['{src,lib}/**'];

/** A trailing mutation range, `file:line[:column]-line[:column]`, on a `mutate` pattern. */
const MUTATION_RANGE_RE = /:\d+(?::\d+)?-\d+(?::\d+)?$/;

/** Suffix of the derived file, which sits next to the tsconfig it derives from. */
const DERIVED_SUFFIX = '.stryker-checker.json';

/** First characters of the derived file: what tells a file this module wrote from one somebody else did. */
const GENERATED_MARKER = '// Generated by withTestFilesExcludedFromTypeCheck()';

/** Start of every line this module logs. */
const LOG_PREFIX = '[Stryker] withTestFilesExcludedFromTypeCheck: ';

/** How many of the errors a derived tsconfig would add the fallback warning quotes. */
const MAX_QUOTED_ERRORS = 3;

/** Options for {@link withTestFilesExcludedFromTypeCheck}. */
export interface TestFilesExcludedFromTypeCheckOptions {
    /** The project directory Stryker runs in (default: `process.cwd()`). */
    cwd?: string
}

/**
 * The parts of a Stryker config read here. PartialStrykerOptions is a deep
 * partial, which lets array items be undefined; Stryker's schema does not.
 */
interface ConfigView {
    mutate?:    string[]
    testFiles?: string[]
    bun?:       { bunArgs?: string[], testFiles?: string[] }
}

/** The project's own typescript, or undefined when it cannot be loaded (then the checker cannot run either). */
function loadTypeScript(cwd: string): TS | undefined {
    try {
        return createRequire(path.join(cwd, 'package.json'))('typescript') as TS;
    } catch{
        return undefined;
    }
}

/**
 * The project `tsconfigPath` describes, with `extends`, `files`, `include` and
 * `exclude` applied by TypeScript itself. A `problem` (the reason, to log)
 * instead when there is nothing this module can safely derive from: a missing
 * or broken tsconfig (left for the checker to report as it always has), or one
 * with project references, which puts the checker in build mode with one
 * program per referenced project. `shown` is how the tsconfig is named in that
 * reason.
 */
function readProject(ts: TS, tsconfigPath: string, shown: string): { project: TypeScript.ParsedCommandLine } | { problem: string } {
    const parsed = ts.getParsedCommandLineOfConfigFile(tsconfigPath, undefined, { ...ts.sys, onUnRecoverableConfigFileDiagnostic: () => undefined });
    if(parsed === undefined) {
        return { problem: `${shown} not found; set tsconfigFile` };
    }
    if(parsed.errors.length > 0) {
        return { problem: `${shown} has errors; fix them (tsc -p ${shown} lists them)` };
    }
    if(parsed.projectReferences !== undefined) {
        return { problem: `${shown} uses project references, which are not supported` };
    }
    return { project: parsed };
}

/**
 * Absolute paths of the files the runner treats as tests: what its discovery
 * finds (Bun's naming rules under `[test].root`), `bun.testFiles`, the
 * `[test].preload` scripts and the files Stryker's `testFiles` patterns match.
 */
async function findTestFiles(config: ConfigView, cwd: string): Promise<Set<string>> {
    const bun = config.bun ?? {};
    const sourceBunfig = bun.bunArgs && splitBunConfigArg(bun.bunArgs).configPath;
    const testFiles = new Set(await readBunfigTestPreloads(cwd, sourceBunfig));
    for(const relativeFiles of [await discoverTestFiles(cwd, undefined, sourceBunfig), bun.testFiles]) {
        if(relativeFiles) {
            for(const file of relativeFiles) {
                testFiles.add(path.resolve(cwd, file));
            }
        }
    }
    if(config.testFiles) {
        for(const file of await glob(config.testFiles, { cwd, absolute: true })) {
            testFiles.add(file);
        }
    }
    return testFiles;
}

/**
 * Absolute paths of the files a positive `mutate` pattern matches. Negations
 * are ignored and ranges stripped: over-matching only keeps a file in the check.
 */
async function findMutateFiles(config: ConfigView, cwd: string): Promise<Set<string>> {
    const patterns = (config.mutate ?? DEFAULT_MUTATE_PATTERNS)
        .filter(pattern => !pattern.startsWith('!'))
        .map(pattern => pattern.replace(MUTATION_RANGE_RE, ''));
    return new Set(await glob(patterns, { cwd, absolute: true }));
}

/** The project's files that another of its files imports, resolved the way TypeScript resolves them. */
function findImportedFiles(ts: TS, project: TypeScript.ParsedCommandLine): Set<string> {
    const imported = new Set<string>();
    for(const file of project.fileNames) {
        for(const { fileName } of ts.preProcessFile(ts.sys.readFile(file)!).importedFiles) {
            const resolved = ts.resolveModuleName(fileName, file, project.options, ts.sys).resolvedModule;
            if(resolved) {
                imported.add(resolved.resolvedFileName);
            }
        }
    }
    return imported;
}

/**
 * Whether a file shapes the types of the files that do not import it: a global
 * script (no imports or exports), or a module with a `declare global` or
 * `declare module "x"` augmentation. Leaving such a file out of the program
 * changes what the rest of the program means, even when only tests import it.
 */
function affectsOtherFiles(ts: TS, file: TypeScript.SourceFile): boolean {
    // eslint-disable-next-line no-bitwise -- node flags are a bitmask
    const isAugmentation = (statement: TypeScript.Statement): boolean => ts.isModuleDeclaration(statement) && (ts.isStringLiteral(statement.name) || (statement.flags & ts.NodeFlags.GlobalAugmentation) !== 0);
    return !ts.isExternalModule(file) || file.statements.some(statement => isAugmentation(statement));
}

/**
 * A program over the project's files. The checker turns `composite` off in
 * single-project mode, and with it on every imported file missing from `files`
 * would be an error, so the programs compared here do the same.
 */
function createProgram(ts: TS, project: TypeScript.ParsedCommandLine, oldProgram?: TypeScript.Program): TypeScript.Program {
    return ts.createProgram({ rootNames: project.fileNames, options: { ...project.options, composite: false }, oldProgram });
}

/** Where an error sits, within its file. */
function errorKey(error: TypeScript.Diagnostic): string {
    return `${error.start}:${error.code}`;
}

/**
 * The type errors the derived program has in files other than tests that the
 * original program does not have in the same place. Only the files with an
 * error in the derived program are checked in the original, so a clean derived
 * program costs one check of the code under test and no more.
 */
function findNewErrors(derived: TypeScript.Program, original: TypeScript.Program, testFiles: ReadonlySet<string>): TypeScript.Diagnostic[] {
    return derived.getSourceFiles()
        .filter(file => !testFiles.has(file.fileName))
        .flatMap(file => derived.getSemanticDiagnostics(file))
        .filter(error => !original.getSemanticDiagnostics(original.getSourceFile(error.file!.fileName)).some(known => errorKey(known) === errorKey(error)));
}

/**
 * Bring the file at `derivedPath` to `text`: nothing is written when it already
 * has that content, and otherwise a temp file is renamed over it, so a reader
 * never sees half a file. Returns why not (as a reason to log) when the file is
 * somebody else's or cannot be read or written.
 */
async function updateDerivedFile(derivedPath: string, shown: string, text: string): Promise<string | undefined> {
    const temp = `${derivedPath}.${process.pid}.tmp`;
    try {
        const existing = await readFile(derivedPath, 'utf8').catch((error: NodeJS.ErrnoException) => {
            if(error.code === 'ENOENT') {
                return undefined;
            }
            throw error;
        });
        if(existing === text) {
            return undefined;
        }
        if(existing !== undefined && !existing.startsWith(GENERATED_MARKER)) {
            return `${shown} exists and was not generated by this helper (rename or delete it)`;
        }
        await writeFile(temp, text);
        await rename(temp, derivedPath);
        return undefined;
    } catch (error) {
        await rm(temp, { force: true });
        return `cannot update ${shown}: ${error instanceof Error ? error.message : String(error)}`;
    }
}

/** Warn why nothing was changed and hand `config` back. */
function leaveUnchanged<C>(config: C, reason: string): C {
    // eslint-disable-next-line no-console -- the one warning this module logs per fallback
    console.warn(`${LOG_PREFIX}not applied: ${reason}`);
    return config;
}

/** Header of the derived tsconfig, which TypeScript reads as JSON with comments. */
function derivedHeader(source: string): string {
    return [
        `${GENERATED_MARKER} from @hughescr/stryker-bun-runner for the`,
        `// TypeScript checker: ${source} minus Bun's test files, their preloads and the files only`,
        '// they import. `files` lists the entry points; TypeScript adds everything they import.',
        '// Rewritten on every Stryker run: do not edit or commit it.',
        '',
    ].join('\n');
}

/** The derived tsconfig's text. */
function renderDerivedTsconfig(sourcePath: string, derivedPath: string, project: TypeScript.ParsedCommandLine, entryPoints: readonly string[]): string {
    const source = path.basename(sourcePath);
    const body = {
        'extends': `./${source}`,
        // In single-project mode the checker turns composite off and deletes declarationDir
        // from the tsconfig it is given. Inherited from the original instead, declarationDir
        // would fail every check (TS5069) wherever composite was what implied declaration.
        ...(project.options.declarationDir !== undefined && { compilerOptions: { declarationDir: null } }),
        include:   [],
        files:     entryPoints.map(file => path.relative(path.dirname(derivedPath), file)),
    };
    return `${derivedHeader(source)}${JSON.stringify(body, null, 2)}\n`;
}

/**
 * Point @stryker-mutator/typescript-checker at a copy of the project's tsconfig
 * without the tests, so mutants are type-checked against the code under test only.
 *
 * Reads the config's `tsconfigFile` (default `tsconfig.json`) with the
 * project's own TypeScript and writes `<name>.stryker-checker.json` next to it.
 * That file extends the original and lists as `files` every file of the project
 * except:
 * - test files, by this runner's rules: Bun's naming rules under bunfig's
 *   `[test].root`, `bun.testFiles` and Stryker's `testFiles` patterns;
 * - bunfig `[test].preload` scripts;
 * - files that only those (and each other) import, such as test helpers,
 *   unless a `mutate` pattern covers them or they shape the types of other
 *   files (a global script, or a `declare global` / `declare module "x"`
 *   augmentation).
 *
 * A file the remaining code imports still comes in through that import, so the
 * program always compiles as before. Before anything is written the derived
 * program is type-checked once, and the derived file is not used if that finds
 * an error in non-test code that the original program does not have. Returns a
 * copy of `config` with `tsconfigFile` set to the derived file and, when
 * `ignorePatterns` is set, a negation for it appended, so Stryker's sandbox
 * gets it too (Stryker rewrites the `tsconfigFile` chain's paths there).
 *
 * Logs one line per call: `console.info` on success, `console.warn` with the
 * reason on every fallback. Returns `config` itself, writing nothing, when
 * `checkers` does not include `typescript`, typescript cannot be loaded from
 * `cwd`, the tsconfig is missing, has errors or uses project references,
 * includes no test files, would be left with no files at all, leaving the tests
 * out adds type errors, or the derived file cannot be written or belongs to
 * somebody else (it has no generated header).
 *
 * @example
 * // stryker.conf.mjs
 * import { withTestFilesExcludedFromTypeCheck } from '@hughescr/stryker-bun-runner';
 * export default await withTestFilesExcludedFromTypeCheck({ testRunner: 'bun', checkers: ['typescript'] });
 */
export async function withTestFilesExcludedFromTypeCheck<T extends PartialStrykerOptions>(config: T, { cwd = process.cwd() }: TestFilesExcludedFromTypeCheckOptions = {}): Promise<T & PartialStrykerOptions> {
    if(!config.checkers?.includes('typescript')) {
        // eslint-disable-next-line no-console -- the one info line this module logs when it has nothing to do
        console.info(`${LOG_PREFIX}not applied: the config's checkers do not include 'typescript'`);
        return config;
    }
    const ts = loadTypeScript(cwd);
    if(!ts) {
        return leaveUnchanged(config, `typescript cannot be loaded from ${cwd}; install it there`);
    }
    const sourcePath = path.resolve(cwd, config.tsconfigFile ?? 'tsconfig.json');
    const shownSource = path.relative(cwd, sourcePath);
    const read = readProject(ts, sourcePath, shownSource);
    if('problem' in read) {
        return leaveUnchanged(config, read.problem);
    }
    const { project } = read;
    const testFiles = await findTestFiles(config as ConfigView, cwd);
    if(!project.fileNames.some(file => testFiles.has(file))) {
        return leaveUnchanged(config, `${shownSource} includes no test files, so there is nothing to exclude`);
    }
    const mutateFiles = await findMutateFiles(config as ConfigView, cwd);
    const importedFiles = findImportedFiles(ts, project);
    const original = createProgram(ts, project);
    const entryPoints = project.fileNames.filter(file => !testFiles.has(file) && (mutateFiles.has(file) || !importedFiles.has(file) || affectsOtherFiles(ts, original.getSourceFile(file)!)));
    if(entryPoints.length === 0) {
        return leaveUnchanged(config, `${shownSource} would have no files left once test files are excluded`);
    }
    const derivedPath = path.join(path.dirname(sourcePath), `${path.basename(sourcePath, '.json')}${DERIVED_SUFFIX}`);
    const shownDerived = path.relative(cwd, derivedPath);
    const text = renderDerivedTsconfig(sourcePath, derivedPath, project, entryPoints);
    const derivedProject = ts.parseJsonSourceFileConfigFileContent(ts.parseJsonText(derivedPath, text), ts.sys, path.dirname(derivedPath), undefined, derivedPath);
    const derived = createProgram(ts, derivedProject, original);
    const newErrors = findNewErrors(derived, original, testFiles);
    if(newErrors.length > 0) {
        const host: TypeScript.FormatDiagnosticsHost = { getCurrentDirectory: () => cwd, getCanonicalFileName: file => file, getNewLine: () => ' ' };
        const quoted = newErrors.slice(0, MAX_QUOTED_ERRORS).map(error => ts.formatDiagnostic(error, host).trim()).join('; ');
        return leaveUnchanged(config, `leaving test files out would add type errors, so ${shownSource} stays in use. First: ${quoted}`);
    }
    const failure = await updateDerivedFile(derivedPath, shownDerived, text);
    if(failure !== undefined) {
        return leaveUnchanged(config, failure);
    }
    const kept = project.fileNames.filter(file => derived.getSourceFile(file) !== undefined).length;
    // eslint-disable-next-line no-console -- the one info line this module logs when it succeeds
    console.info(`${LOG_PREFIX}using ${shownDerived}, ${project.fileNames.length - kept} test/helper files excluded, ${kept} files kept`);
    return {
        ...config,
        tsconfigFile: shownDerived,
        ...(config.ignorePatterns && { ignorePatterns: [...config.ignorePatterns, `!${shownDerived}`] }),
    };
}
